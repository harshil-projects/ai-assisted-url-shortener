-- V1: links and click events (greenfield, task T-002).
-- Written in the SQL subset accepted by both H2 in PostgreSQL mode and PostgreSQL:
-- identity columns, TIMESTAMP WITH TIME ZONE, named constraints, one statement per change.

CREATE TABLE links (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          VARCHAR(32)   NOT NULL,
    original_url  VARCHAR(2048) NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_links_code UNIQUE (code)
);

CREATE TABLE click_events (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    link_id      BIGINT NOT NULL,
    occurred_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_click_events_link FOREIGN KEY (link_id) REFERENCES links (id) ON DELETE CASCADE
);

-- Serves the stats query: count, windowed counts, and max(occurred_at) for one link.
CREATE INDEX ix_click_events_link_time ON click_events (link_id, occurred_at);
