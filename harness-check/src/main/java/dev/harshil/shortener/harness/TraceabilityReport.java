package dev.harshil.shortener.harness;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.util.OptionalDouble;
import java.util.function.Predicate;
import java.util.function.ToLongFunction;
import java.util.regex.Pattern;
import java.util.stream.Stream;

/**
 * Writes the traceability report as deterministic Markdown: no timestamps, tasks sorted by id,
 * computed figures labelled apart from engineer-asserted ones.
 */
public final class TraceabilityReport {

  /** The last line of every report, naming which figures are asserted and which are computed. */
  public static final String CLOSING_LINE =
      "Statuses and rationale are engineer-asserted; kept ratios and counts are computed.";

  private static final Pattern PROMPT_VERSION = Pattern.compile("v\\d+\\.md");
  private static final String NOT_AVAILABLE = "n/a";
  private static final String ASSERTED = "engineer-asserted";
  private static final String COMPUTED = "computed";

  private record Row(
      String id,
      String activities,
      String impact,
      String status,
      long promptVersions,
      long generated,
      long edited,
      long rejected,
      OptionalDouble keptRatio,
      String gate,
      boolean signedOff,
      long commits) {}

  private TraceabilityReport() {}

  /** Renders the report and writes it to the target file, creating parent directories. */
  public static Path write(HarnessRepo repo, GitLog gitLog, Path target) throws IOException {
    Path absolute = target.toAbsolutePath().normalize();
    Files.createDirectories(absolute.getParent());
    Files.writeString(absolute, render(repo, gitLog), StandardCharsets.UTF_8);
    return absolute;
  }

  /** Renders the report as Markdown. */
  public static String render(HarnessRepo repo, GitLog gitLog) {
    List<Row> rows = new ArrayList<>();
    for (TaskSpec task : repo.tasks()) {
      rows.add(row(repo, gitLog, task));
    }
    StringBuilder md = new StringBuilder();
    md.append("# Traceability report\n\n");
    md.append("Generated by harness-check from the data under `harness/`, the working tree, and ");
    md.append("git history after the `baseline` tag.\n\n");
    appendTaskTable(md, rows, gitLog);
    appendSummary(md, rows, gitLog);
    md.append(CLOSING_LINE).append('\n');
    return md.toString();
  }

  private static Row row(HarnessRepo repo, GitLog gitLog, TaskSpec task) {
    String id = task.key();
    List<LedgerEntry> entries = repo.ledger().entriesFor(id);
    List<GateRecord> gates = repo.ledger().gatesFor(id);
    return new Row(
        id,
        task.activities().isEmpty() ? NOT_AVAILABLE : String.join(", ", task.activities()),
        orNotAvailable(task.impact()),
        orNotAvailable(task.status()),
        promptVersions(repo.promptsDir().resolve(id)),
        countFiles(entries, "generated"),
        countFiles(entries, "edited"),
        countFiles(entries, Vocabulary.REJECTED),
        KeptRatio.compute(repo, id, entries),
        gates.isEmpty() ? "none" : orNotAvailable(gates.get(gates.size() - 1).overall()),
        !repo.ledger().signoffsFor(id).isEmpty(),
        gitLog.commitsFor(id).size());
  }

  private static void appendTaskTable(StringBuilder md, List<Row> rows, GitLog gitLog) {
    md.append("## Tasks\n\n");
    md.append("| Task | Activities | Impact | Status | Prompt versions | Generated | Edited ");
    md.append("| Rejected | Kept ratio | Gate | Sign-off | Commits |\n");
    md.append("|---|---|---|---|---|---|---|---|---|---|---|---|\n");
    for (Row row : rows) {
      md.append("| ").append(row.id());
      md.append(" | ").append(row.activities());
      md.append(" | ").append(row.impact());
      md.append(" | ").append(row.status());
      md.append(" | ").append(row.promptVersions());
      md.append(" | ").append(row.generated());
      md.append(" | ").append(row.edited());
      md.append(" | ").append(row.rejected());
      md.append(" | ").append(ratio(row.keptRatio()));
      md.append(" | ").append(row.gate());
      md.append(" | ").append(row.signedOff() ? "yes" : "no");
      md.append(" | ").append(gitLog.skipped() ? NOT_AVAILABLE : String.valueOf(row.commits()));
      md.append(" |\n");
    }
    if (rows.isEmpty()) {
      md.append("\nNo task specs found under `harness/tasks/`.\n");
    }
    md.append('\n');
  }

  private static void appendSummary(StringBuilder md, List<Row> rows, GitLog gitLog) {
    md.append("## Summary\n\n");
    md.append("| Measure | Value | Source |\n|---|---|---|\n");
    summaryRow(md, "Tasks", String.valueOf(rows.size()), COMPUTED);
    String done = countRows(rows, row -> Vocabulary.DONE.equals(row.status()));
    summaryRow(md, "Tasks done", done, ASSERTED);
    String high = countRows(rows, row -> Vocabulary.HIGH.equals(row.impact()));
    summaryRow(md, "High-impact tasks", high, ASSERTED);
    summaryRow(md, "Tasks with sign-off", countRows(rows, Row::signedOff), COMPUTED);
    appendFileFigures(md, rows);
    summaryRow(md, "Mean kept ratio", ratio(meanKeptRatio(rows)), COMPUTED);
    String commits =
        gitLog.skipped()
            ? NOT_AVAILABLE + " (" + gitLog.skipReason() + ")"
            : String.valueOf(gitLog.commits().size());
    summaryRow(md, "Commits after baseline", commits, COMPUTED);
    md.append('\n');
  }

  private static void appendFileFigures(StringBuilder md, List<Row> rows) {
    long generated = sum(rows, Row::generated);
    summaryRow(md, "Files kept as generated", String.valueOf(generated), ASSERTED);
    long edited = sum(rows, Row::edited);
    summaryRow(md, "Files edited", String.valueOf(edited), ASSERTED);
    long rejected = sum(rows, Row::rejected);
    summaryRow(md, "Files rejected", String.valueOf(rejected), ASSERTED);
    long files = generated + edited + rejected;
    summaryRow(md, "Acceptance ratio", share(generated, files), COMPUTED);
    summaryRow(md, "Edit ratio", share(edited, files), COMPUTED);
    summaryRow(md, "Rejection ratio", share(rejected, files), COMPUTED);
  }

  private static void summaryRow(StringBuilder md, String measure, String value, String source) {
    md.append("| ").append(measure).append(" | ").append(value).append(" | ").append(source);
    md.append(" |\n");
  }

  private static long promptVersions(Path directory) {
    if (!Files.isDirectory(directory)) {
      return 0;
    }
    try (Stream<Path> files = Files.list(directory)) {
      return files
          .filter(file -> PROMPT_VERSION.matcher(file.getFileName().toString()).matches())
          .count();
    } catch (IOException e) {
      return 0;
    }
  }

  private static OptionalDouble meanKeptRatio(List<Row> rows) {
    return rows.stream()
        .map(Row::keptRatio)
        .filter(OptionalDouble::isPresent)
        .mapToDouble(OptionalDouble::getAsDouble)
        .average();
  }

  private static long countFiles(List<LedgerEntry> entries, String status) {
    return entries.stream().mapToLong(entry -> entry.countFiles(status)).sum();
  }

  private static String countRows(List<Row> rows, Predicate<Row> predicate) {
    return String.valueOf(rows.stream().filter(predicate).count());
  }

  private static long sum(List<Row> rows, ToLongFunction<Row> field) {
    return rows.stream().mapToLong(field).sum();
  }

  private static String share(long part, long whole) {
    return whole == 0 ? NOT_AVAILABLE : ratio(OptionalDouble.of((double) part / whole));
  }

  private static String ratio(OptionalDouble value) {
    return value.isPresent()
        ? String.format(Locale.ROOT, "%.2f", value.getAsDouble())
        : NOT_AVAILABLE;
  }

  private static String orNotAvailable(String value) {
    return value == null || value.isBlank() ? NOT_AVAILABLE : value;
  }
}
